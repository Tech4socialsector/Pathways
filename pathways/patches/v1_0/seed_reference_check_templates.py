def execute():
	seed_reference_check_templates()


def seed_reference_check_templates():
	for spec in REFERENCE_CHECK_TEMPLATES:
		if frappe.db.exists("Reference Check Template", spec["template_name"]):
			continue
		if not frappe.db.exists("Recruitment Track", spec["track"]):
			continue
		frappe.get_doc(
			{
				"doctype": "Reference Check Template",
				"template_name": spec["template_name"],
				"track": spec["track"],
				"is_active": 1,
				"intro_text": spec["intro_text"],
				"questions": [
					{"sequence": idx, "section": section, "question": question, "answer_type": answer_type, "required": required}
					for idx, (section, question, answer_type, required) in enumerate(spec["questions"], start=1)
				],
			}
		).insert(ignore_permissions=True)
